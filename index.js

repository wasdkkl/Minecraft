function logAndEmit(msg) {
  console.log(msg);
  io.emit('log', msg);
}

function initBot() {
  logAndEmit('⏳ [CONNECTING] Menghubungkan bot ke server...');

  bot = mineflayer.createBot(botOptions);

  bot.on('spawn', () => {
    logAndEmit('🚀 [SPAWN] Bot berhasil masuk ke dalam game!');
    
    // Matikan physics di awal agar tidak terkena anti-cheat kick
    bot.physicsEnabled = false;

    // Aktifkan fisika & Anti-AFK setelah 10 detik secara aman
    setTimeout(() => {
      bot.physicsEnabled = true;
      logAndEmit('✅ [PHYSICS] Fisika bot diaktifkan.');
      
      setInterval(() => {
        if (bot && bot.entity) {
          bot.setControlState('jump', true);
          setTimeout(() => bot.setControlState('jump', false), 400);
        }
      }, 20000); // Melompat tiap 20 detik
    }, 10000);
  });

  // Menerima pesan chat dari server
  bot.on('message', (jsonMsg) => {
    const rawMsg = jsonMsg.toString().trim();
    if (rawMsg) {
      logAndEmit('[CHAT] ' + rawMsg);

      // Auto-accept TPA jika ada pesan teleportasi
      if (rawMsg.includes('has requested to teleport') || rawMsg.toLowerCase().includes('tpa')) {
        logAndEmit('🔄 [AUTO-TPA] Mendeteksi permintaan TPA, mengirim /tpaccept...');
        setTimeout(() => {
          if (bot) bot.chat('/tpaccept');
        }, 2000);
      }
    }
  });

  bot.on('end', (reason) => {
    logAndEmit(`❌ [DISCONNECT] Terputus dari server (Alasan: ${reason}). Reconnecting dalam 15s...`);
    setTimeout(initBot, 15000);
  });

  bot.on('error', (err) => {
    logAndEmit(`⚠️ [ERROR] ${err.message}`);
  });
}

// Menangani Perintah dari Web Live Console
io.on('connection', (socket) => {
  socket.emit('log', '🌐 Connected to Bot Live Web Console');

  socket.on('sendCommand', (cmd) => {
    if (bot) {
      bot.chat(cmd);
      logAndEmit(`[WEB-CMD] Mengirim perintah: ${cmd}`);
    } else {
      socket.emit('log', '⚠️ Bot belum siap atau belum terhubung.');
    }
  });
});

// Jalankan Web Server
server.listen(PORT, () => {
  console.log(`🌐 Web Dashboard aktif di port ${PORT}`);
  initBot();
});
